const FEE_BEARING = new Set([
  'Dexs',
  'Lending',
  'Derivatives',
  'CDP',
  'Yield',
  'Leveraged Farming',
  'Uncollateralized Lending',
  'Collateral Markets',
  'Interest Rate Derivatives',
  'Basis Trading',
]);

