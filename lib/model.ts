// Token launch radar, model radar-2.
//
// The board ranks every pre-token protocol the snapshot can still describe as a launch
// candidate: it records no token (no market cap, no CoinGecko id, no symbol) and it is not a
// wrapped, staked or bridged product of a token that already trades. That second rule is the
// snapshot's own watchlist rule, applied to the whole board: a bridge's TVL is another token's
// TVL, a staked product is its underlying token, and a versioned pool is a later release of a
// protocol that already launched. Those protocols are not hidden: the dashboard lists them in a
// "set aside" view with the reason each one was set aside, and the live-token protocols are
// listed beside them with their market caps. The ranked board holds only launches that may
// still be ahead.
//
// Implied value follows only from the snapshot's own figures, one function for every row:
//
//   base      = tvl_usd x 0.25
//   growth    = clamp(change_7d, -80, 200) per cent
//   growthMul = 1 + (growth / 100) x 0.7
//   maturity  = 0.55 + min(age_days, 1460) / 1460 x 0.45   (age unknown: 365 days)
//   category  = 1.12 fee-bearing, 1.06 allocator / curator, 1.00 everything else
//   chains    = 1 + 0.02 x min(chains - 1, 5)
//   implied   = max(1, round(base x growthMul x maturity x category x chains))
//
// Every multiplier is rounded to 4 decimals before the product, so the dashboard page
// recomputes exactly the number board.json carries. No protocol name is ever special-cased:
// the same function scores every row, and the ranking is the model's claim, not a hand list.
// A protocol that records no token is described as recording none, never as having none:
// DefiLlama's record is not proof.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

